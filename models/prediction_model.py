"""
prediction_model.py - SQLAlchemy model for the PREDICTION table.

Each row stores the result of one AI analysis cycle for a given image:
  - HuggingFace classification label + confidence
  - Claude-generated clinical report
  - Which model was used

Multiple predictions per image are allowed (each view/re-analysis creates one).

Columns:
  prediction_id   Integer, PK, auto-increment
  image_id        Integer, FK → image.image_id
  patient_id      Integer, FK → patient.patient_id
  label           String(200)   — top classification label from HuggingFace
  confidence      Float         — confidence score 0.0 – 1.0
  report          Text          — full clinical report from Claude
  model_used      String(200)   — HuggingFace model ID used for analysis
  created_at      DateTime      — UTC, auto-set
"""

import datetime
from utils.db import db


class Prediction(db.Model):
    __tablename__ = "prediction"

    prediction_id = db.Column(db.Integer, primary_key=True, autoincrement=True)

    image_id = db.Column(
        db.Integer,
        db.ForeignKey("image.image_id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    patient_id = db.Column(
        db.Integer,
        db.ForeignKey("patient.patient_id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    label = db.Column(db.String(200), nullable=False)
    confidence = db.Column(db.Float, nullable=False)

    # Full structured clinical report generated by Claude
    report = db.Column(db.Text, nullable=True)

    # HuggingFace model identifier (from HF_MODEL_ID env var)
    model_used = db.Column(db.String(200), nullable=True)

    created_at = db.Column(
        db.DateTime,
        nullable=False,
        default=datetime.datetime.utcnow,
        index=True,
    )

    # ── Relationships ─────────────────────────────────────────────────────
    image = db.relationship("Image", backref=db.backref("predictions", lazy=True))
    patient = db.relationship("Patient", backref=db.backref("predictions", lazy=True))

    # ── Helpers ───────────────────────────────────────────────────────────
    def to_dict(self) -> dict:
        return {
            "prediction_id": self.prediction_id,
            "image_id": self.image_id,
            "patient_id": self.patient_id,
            "label": self.label,
            "confidence": round(self.confidence, 6),
            "confidence_pct": f"{self.confidence * 100:.2f}%",
            "model_used": self.model_used,
            "created_at": self.created_at.isoformat(),
            # Note: report is returned separately to keep prediction summary concise
        }

    def __repr__(self) -> str:
        return (
            f"<Prediction id={self.prediction_id} image={self.image_id} "
            f"label={self.label!r} conf={self.confidence:.2f}>"
        )
